// Flip Book data for the app: library designs (61 + 60 live), reader looks.
// usage: node tool/gen_fb_data.js ../bizhub/src lib/features/flipbook/fb_data.dart
const fs = require("fs");
const SRC = (process.argv[2] || "../bizhub/src").replace(/\/?$/, "/");
const load = (f, names) => {
  const src = fs.readFileSync(SRC + f, "utf8").replace(/^import [\s\S]*?;$/gm, "").replace(/export (const|function) /g, "$1 ").replace(/^export \{.*$/gm, "");
  const m = { exports: {} };
  new Function("module", "document", src + `\nmodule.exports = { ${names.join(", ")} };`)(m, undefined);
  return m.exports;
};
const { SHELVES, LIVE } = load("fbook/shelves.js", ["SHELVES", "LIVE"]);
const { READERS } = load("fbook/readers.js", ["READERS"]);
const q = (s) => JSON.stringify(s ?? "").replace(/\$/g, "\\$");
// every colour in a CSS value → 0xAARRGGBB
const cols = (css) => {
  const out = [];
  for (const m of String(css).matchAll(/#([0-9a-f]{3,8})\b|rgba?\(([^)]+)\)/gi)) {
    if (m[1]) {
      let h = m[1];
      if (h.length === 3) h = h.split("").map((c) => c + c).join("");
      out.push(`0xFF${h.slice(0, 6).toUpperCase()}`);
    } else {
      const p = m[2].split(",").map((x) => parseFloat(x));
      const a = Math.round((p[3] ?? 1) * 255);
      out.push(`0x${[a, p[0], p[1], p[2]].map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase()}`);
    }
  }
  return out;
};
const one = (css) => cols(css)[0] || "0xFFFFFFFF";
let out = `// GENERATED by tool/gen_fb_data.js from the web source — do not edit by hand.\n// ignore_for_file: prefer_single_quotes\n\n`;
out += `class FbShelf {\n  final String en, km, layout, pat, live, hf, bf;\n  final int bg, surface, ink, muted, accent, fx;\n  final List<int> plank;\n  final bool dark;\n  const FbShelf(this.en, this.km, this.layout, this.bg, this.surface, this.ink, this.muted, this.accent, this.plank, this.pat, this.dark, this.hf, this.bf, {this.live = '', this.fx = 0});\n  String name(String lang) => lang == 'km' ? km : en;\n  bool get isLive => live.isNotEmpty;\n}\n\nconst fbShelves = <String, FbShelf>{\n`;
for (const [k, t] of Object.entries(SHELVES)) {
  const live = LIVE[k] ? `, live: ${q(t.live)}, fx: ${one(t.fx)}` : "";
  out += `  ${q(k)}: FbShelf(${q(t.en)}, ${q(t.km)}, ${q(t.layout)}, ${one(t.bg)}, ${one(t.surface)}, ${one(t.ink)}, ${one(t.muted)}, ${one(t.accent)}, [${cols(t.plank).join(", ")}], ${q(t.pat)}, ${!!t.dark}, ${q(t.hf)}, ${q(t.bf)}${live}),\n`;
}
out += `};\n\nclass FbReader {\n  final String en, km;\n  final List<int> bg;\n  final int bar, ink, muted;\n  final bool dark;\n  const FbReader(this.en, this.km, this.bg, this.bar, this.ink, this.muted, this.dark);\n  String name(String lang) => lang == 'km' ? km : en;\n}\n\nconst fbReaders = <String, FbReader>{\n`;
for (const [k, r] of Object.entries(READERS)) out += `  ${q(k)}: FbReader(${q(r.en)}, ${q(r.km)}, [${cols(r.bg).filter((c) => !c.startsWith("0x00")).join(", ")}], ${one(r.bar)}, ${one(r.ink)}, ${one(r.muted)}, ${!!r.dark}),\n`;
out += `};\n`;
fs.writeFileSync(process.argv[3], out);
console.log("shelves", Object.keys(SHELVES).length, "live", Object.keys(LIVE).length, "readers", Object.keys(READERS).length);
