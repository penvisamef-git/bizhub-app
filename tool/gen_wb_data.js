// Website Builder data for the app: blocks (fields + new-block content), looks (353), categories, styles, fonts, colours.
// usage: node tool/gen_wb_data.js ../bizhub/src lib/features/website/wb_data.dart
const fs = require("fs");
const SRC = (process.argv[2] || "../bizhub/src").replace(/\/?$/, "/");
const load = (f, names, pre = "") => {
  let src = fs.readFileSync(SRC + f, "utf8").replace(/^import [\s\S]*?;$/gm, "").replace(/export (const|function) /g, "$1 ").replace(/^export \{.*$/gm, "");
  const m = { exports: {} };
  new Function("module", pre + src + `\nmodule.exports = { ${names.join(", ")} };`)(m);
  return m.exports;
};
const B = load("wsite/blocks.js", ["BLOCKS", "BLOCK_GROUPS", "newBlock"]);
const L = load("wsite/themeList.js", ["WS_THEME_DATA", "WS_THEME_CATS", "WS_THEME_STYLES", "WS_THEME_ALIAS", "WS_THEME_DESC"]);
const T = load("wsite/themes.js", ["WS_FREE", "WS_FONTS", "WS_FREE_FONTS", "WS_COLORS"], "const { WS_THEME_ALIAS, WS_THEME_CATS, WS_THEME_DATA, WS_THEME_DESC, WS_THEME_STYLES } = __L;\n".replace("__L", JSON.stringify(L)));
const q = (s) => JSON.stringify(s ?? "").replace(/\$/g, "\\$");
const col = (h) => {
  let x = String(h || "#000000").replace("#", "");
  if (x.length === 3) x = x.split("").map((c) => c + c).join("");
  return `0xFF${x.toUpperCase()}`;
};
const dart = (v) => {
  if (Array.isArray(v)) return `[${v.map(dart).join(", ")}]`;
  if (v && typeof v === "object") return `{${Object.entries(v).map(([k, x]) => `${q(k)}: ${dart(x)}`).join(", ")}}`;
  if (typeof v === "string") return q(v);
  return String(v);
};
let out = `// GENERATED by tool/gen_wb_data.js from the web source — do not edit by hand.\n// ignore_for_file: prefer_single_quotes\nimport 'dart:convert';\n\n`;
out += `// block fields — t / tl = text in both languages, s = plain text, img, to = a link, date, bool, [..] = choice, {list, max} = rows\nconst wbBlocks = <String, Map<String, dynamic>>${dart(B.BLOCKS)};\n\n`;
out += `const wbBlockGroups = <(String, List<String>)>[${B.BLOCK_GROUPS.map(([g, l]) => `(${q(g)}, ${dart(l)})`).join(", ")}];\n\n`;
const defs = Object.fromEntries(Object.keys(B.BLOCKS).map((k) => [k, B.newBlock(k).data]));
out += `// the content of a new block\nfinal wbNewData = (jsonDecode(${q(JSON.stringify(defs))}) as Map).cast<String, dynamic>();\n\n`;
out += `class WbTheme {\n  final String en, km, cat, font, btn;\n  final int c, c2, bg, sf, ink, r;\n  final bool dark;\n  final Map<String, String> parts;\n  const WbTheme(this.en, this.km, this.cat, this.c, this.c2, this.bg, this.sf, this.ink, this.dark, this.r, this.btn, this.font, this.parts);\n  String name(String lang) => lang == 'km' ? km : en;\n}\n\n`;
const partKeys = ["header", "hero", "sections", "cards", "deco", "titles", "btns", "divider", "pics", "bgfx", "type", "width", "density", "foot", "style"];
out += `const wbThemes = <String, WbTheme>{\n`;
for (const [k, t] of Object.entries(L.WS_THEME_DATA)) {
  const parts = Object.fromEntries(partKeys.filter((p) => t[p]).map((p) => [p, t[p]]));
  out += `  ${q(k)}: WbTheme(${q(t.en)}, ${q(t.km)}, ${q(t.cat)}, ${col(t.c)}, ${col(t.c2)}, ${col(t.bg)}, ${col(t.sf)}, ${col(t.ink)}, ${!!t.dark}, ${t.r}, ${q(t.btn)}, ${q(t.font)}, ${dart(parts)}),\n`;
}
out += `};\nconst wbThemeAlias = <String, String>${dart(L.WS_THEME_ALIAS)};\n`;
out += `String wbThemeKey(String k) => wbThemes.containsKey(k) ? k : (wbThemes.containsKey(wbThemeAlias[k]) ? wbThemeAlias[k]! : 'clean');\nWbTheme wbTheme(String k) => wbThemes[wbThemeKey(k)]!;\n\n`;
out += `const wbThemeCats = <(String, String, String)>[${L.WS_THEME_CATS.map((c) => `(${q(c.key)}, ${q(c.en)}, ${q(c.km)})`).join(", ")}];\n`;
out += `const wbThemeStyles = <(String, String, String)>[${L.WS_THEME_STYLES.map((c) => `(${q(c.key)}, ${q(c.en)}, ${q(c.km)})`).join(", ")}];\n`;
out += `// words for a look's description: part → value → [en, km]\nconst wbThemeDesc = <String, Map<String, dynamic>>${dart(L.WS_THEME_DESC)};\n\n`;
out += `const wbFreeThemes = ${dart(T.WS_FREE)};\nconst wbFreeFonts = ${dart(T.WS_FREE_FONTS)};\nconst wbColors = ${dart(T.WS_COLORS)};\n`;
out += `const wbFonts = <String, (String, String)>{${Object.entries(T.WS_FONTS).map(([k, f]) => `${q(k)}: (${q(f.en)}, ${q(f.km)})`).join(", ")}};\n`;
fs.writeFileSync(process.argv[3], out);
console.log("themes", Object.keys(L.WS_THEME_DATA).length, "blocks", Object.keys(B.BLOCKS).length);
