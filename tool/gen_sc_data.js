// Loyalty Stamp Card designs for the app, made from the web's own list (bizhub/src/stamp/designs.js).
// usage: node tool/gen_sc_data.js ../bizhub/src lib/features/stamp/sc_data.dart
const fs = require("fs");
const SRC = (process.argv[2] || "../bizhub/src").replace(/\/?$/, "/");
const OUT = process.argv[3] || "lib/features/stamp/sc_data.dart";
const src = fs.readFileSync(SRC + "stamp/designs.js", "utf8");
const grab = (name) => {
  const at = src.indexOf(`export const ${name} =`);
  if (at < 0) throw new Error("not found: " + name);
  const start = src.indexOf("{", at);
  const end = src.indexOf(";\n", start);
  return JSON.parse(src.slice(start, end));
};
const THEMES = grab("SC_THEMES_DATA");
const POSTERS = grab("SC_POSTERS");
const PALETTES = grab("SC_POSTER_PALETTES");

const hex = (h) => {
  let v = h.replace("#", "");
  if (v.length === 3) v = v.split("").map((c) => c + c).join("");
  return `Color(0xFF${v.toUpperCase()})`;
};
function color(c) {
  c = String(c).trim();
  if (c.startsWith("#")) return hex(c);
  const m = c.match(/rgba?\(([^)]+)\)/);
  if (m) {
    const [r, g, b, a = "1"] = m[1].split(",").map((x) => x.trim());
    return `Color.fromRGBO(${r}, ${g}, ${b}, ${Number(a)})`;
  }
  throw new Error("colour? " + c);
}
// "#fff" or "linear-gradient(160deg,#a 0%,#b 100%)" → angle + colours
function bg(v) {
  const m = String(v).match(/linear-gradient\((\d+)deg,(.+)\)$/);
  if (!m) return { angle: 0, colors: [color(v)] };
  const stops = m[2].split(/,(?![^(]*\))/).map((s) => s.trim().split(/\s+/)[0]);
  return { angle: Number(m[1]), colors: stops.map(color) };
}
const q = (s) => `'${String(s ?? "").replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

let out = `// GENERATED by tool/gen_sc_data.js from bizhub/src/stamp/designs.js — do not edit by hand.
// Loyalty Stamp Card: ${Object.keys(THEMES).length} card designs, ${Object.keys(POSTERS).length} shop QR posters, ${Object.keys(PALETTES).length} poster colours.
import 'package:flutter/painting.dart';

class ScTheme {
  final String key, tier, en, km, pat;
  final double angle; // CSS degrees
  final List<Color> bg;
  final Color ink, muted, accent, slot, line;
  final bool dark;
  const ScTheme({required this.key, required this.tier, required this.en, required this.km, required this.angle, required this.bg, required this.ink, required this.muted, required this.accent, required this.slot, required this.line, this.dark = false, this.pat = ''});
}

class ScPoster {
  final String key, tier, en, km, layout, pal;
  const ScPoster({required this.key, required this.tier, required this.en, required this.km, required this.layout, required this.pal});
}

class ScPalette {
  final String en, km;
  final Color bg1, bg2, ink, muted, accent, paper;
  const ScPalette({required this.en, required this.km, required this.bg1, required this.bg2, required this.ink, required this.muted, required this.accent, required this.paper});
}

const scThemes = <String, ScTheme>{
`;
for (const [k, t] of Object.entries(THEMES)) {
  const b = bg(t.bg);
  out += `  ${q(k)}: ScTheme(key: ${q(k)}, tier: ${q(t.tier)}, en: ${q(t.en)}, km: ${q(t.km)}, angle: ${b.angle}, bg: [${b.colors.join(", ")}], ink: ${color(t.ink)}, muted: ${color(t.muted)}, accent: ${color(t.accent)}, slot: ${color(t.slot)}, line: ${color(t.line)}${t.dark ? ", dark: true" : ""}${t.pat ? `, pat: ${q(t.pat)}` : ""}),\n`;
}
out += `};

const scPosters = <String, ScPoster>{
`;
for (const [k, p] of Object.entries(POSTERS)) out += `  ${q(k)}: ScPoster(key: ${q(k)}, tier: ${q(p.tier)}, en: ${q(p.en)}, km: ${q(p.km)}, layout: ${q(p.layout)}, pal: ${q(p.pal)}),\n`;
out += `};

const scPalettes = <String, ScPalette>{
`;
for (const [k, p] of Object.entries(PALETTES)) out += `  ${q(k)}: ScPalette(en: ${q(p.en)}, km: ${q(p.km)}, bg1: ${color(p.bg1)}, bg2: ${color(p.bg2)}, ink: ${color(p.ink)}, muted: ${color(p.muted)}, accent: ${color(p.accent)}, paper: ${color(p.paper)}),\n`;
out += `};
`;
fs.mkdirSync(require("path").dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(Object.keys(THEMES).length, "themes,", Object.keys(POSTERS).length, "posters,", Object.keys(PALETTES).length, "palettes →", OUT);
