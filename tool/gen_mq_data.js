// Menu QR looks → lib/features/menuqr/mq_data.dart
// usage: node tool/gen_mq_data.js ../bizhub/src lib/features/menuqr/mq_data.dart
const fs = require("fs");
const path = require("path");
const [src, out] = process.argv.slice(2);
(async () => {
  const tmp = path.join(require("os").tmpdir(), `mqthemes-${Date.now()}.mjs`);
  fs.copyFileSync(path.join(src, "qmenu/themes.js"), tmp);
  const { MQ_THEMES, MQ_THEME_KEYS } = await import(tmp);
  fs.unlinkSync(tmp);
  const hex = (h) => `0xFF${String(h || "#000000").replace("#", "").toUpperCase().padEnd(6, "0").slice(0, 6)}`;
  const q = (s) => `'${String(s || "").replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  const rows = MQ_THEME_KEYS.map((k) => {
    const t = MQ_THEMES[k];
    return `  ${q(k)}: MqLook(${q(t.t)}, ${q(t.en)}, ${q(t.km)}, ${q(t.layout)}, ${q(t.head)}, ${hex(t.bg)}, ${hex(t.card)}, ${hex(t.ink)}, ${hex(t.muted)}, ${hex(t.accent)}, ${hex(t.line)}, ${t.r ?? 14}, ${!!t.dark}, ${q(t.d_en)}, ${q(t.d_km)}, ${q(t.tabs)}, ${q(t.price)}),`;
  });
  const dart = `// GENERATED by tool/gen_mq_data.js from bizhub/src/qmenu/themes.js — do not edit by hand.
// Menu QR looks: tier (free / basic / pro), names, layout + header, colours.

class MqLook {
  final String tier, en, km, layout, head;
  final int bg, card, ink, muted, accent, line;
  final num r;
  final bool dark;
  final String dEn, dKm, tabs, price;
  const MqLook(this.tier, this.en, this.km, this.layout, this.head, this.bg, this.card, this.ink, this.muted, this.accent, this.line, this.r, this.dark, this.dEn, this.dKm, this.tabs, this.price);
  String name(String lang) => lang == 'km' ? km : en;
  String desc(String lang) => lang == 'km' ? dKm : dEn;
}

const mqLooks = <String, MqLook>{
${rows.join("\n")}
};
`;
  fs.writeFileSync(out, dart);
  console.log(MQ_THEME_KEYS.length, "looks");
})();
