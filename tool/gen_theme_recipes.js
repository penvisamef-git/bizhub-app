// Makes lib/features/namecard/recipes_data.dart from the web's theme list (bizhub/src/namecard/themeRecipes.json).
//   node tool/gen_theme_recipes.js [path/to/themeRecipes.json]
const fs = require("fs");
const path = require("path");
const src = process.argv[2] || path.join(__dirname, "../../bizhub/src/namecard/themeRecipes.json");
const j = JSON.parse(fs.readFileSync(src, "utf8"));
const q = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$") + "'";
const list = (name, part) => {
  const rows = part.themes.map((t) => `  ${q(t.key)}: Recipe(${q(t.en)}, ${q(t.km)}, {${part.parts.map((p) => `${q(p)}: ${q(t[p])}`).join(", ")}}),`);
  return `const ${name} = <String, Recipe>{\n${rows.join("\n")}\n};\n`;
};
const out = `// GENERATED by tool/gen_theme_recipes.js from bizhub/src/namecard/themeRecipes.json — do not edit by hand.
// The 100 name card + 100 portfolio theme recipes (spec: bizhub/src/namecard/THEME_RECIPES.md).

class Recipe {
  final String en, km;
  final Map<String, String> parts;
  const Recipe(this.en, this.km, this.parts);
  String name(bool kmLang) => kmLang ? km : en;
  String operator [](String part) => parts[part] ?? '';
}

${list("cardRecipes", j.card)}
${list("pfRecipes", j.portfolio)}`;
fs.writeFileSync(path.join(__dirname, "../lib/features/namecard/recipes_data.dart"), out);
console.log("cards", j.card.themes.length, "portfolio", j.portfolio.themes.length);
