// Super admin data shared with the web → lib/features/admin/admin_data.dart
// usage: node tool/gen_admin_data.js ../bizhub/src lib/features/admin/admin_data.dart
const fs = require("fs");
const path = require("path");
const os = require("os");
const [src, out] = process.argv.slice(2);
const load = async (rel) => {
  const tmp = path.join(os.tmpdir(), `adm-${Date.now()}-${Math.random().toString(36).slice(2)}.mjs`);
  fs.copyFileSync(path.join(src, rel), tmp);
  try {
    return await import(tmp);
  } finally {
    fs.unlinkSync(tmp);
  }
};
(async () => {
  const { PRICE_GROUPS } = await load("dashboard/admin/prices/catalog.js");
  const { DEFAULT_HOMEPAGE } = await load("homepage/defaults.js");
  const { HOME_TEXT, SERVICE_DETAILS } = await load("homepage/content.js");
  const strings = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => typeof v === "string"));
  const titles = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, v?.title || k]));
  const data = {
    price_groups: PRICE_GROUPS,
    default_homepage: DEFAULT_HOMEPAGE,
    home_text: { en: strings(HOME_TEXT.en), km: strings(HOME_TEXT.km) },
    service_titles: { en: titles(SERVICE_DETAILS.en), km: titles(SERVICE_DETAILS.km) },
  };
  const json = JSON.stringify(data);
  if (json.includes("'''")) throw new Error("triple quote in data");
  const dart = `// GENERATED by tool/gen_admin_data.js from bizhub/src (prices/catalog.js, homepage/defaults.js, homepage/content.js) — do not edit by hand.
import 'dart:convert';

import '../../core/api.dart';

final Json adminData = obj(jsonDecode(_raw));

List<Json> get priceGroups => objs(adminData['price_groups']);
Json get defaultHomepage => obj(adminData['default_homepage']);
Map<String, String> homeText(String lang) => obj(obj(adminData['home_text'])[lang]).map((k, v) => MapEntry(k, '\$v'));
String serviceTitle(String lang, String key) => str(obj(obj(adminData['service_titles'])[lang])[key]);

const _raw = r'''${json}''';
`;
  fs.writeFileSync(out, dart);
  console.log(PRICE_GROUPS.length, "price groups", Object.keys(data.home_text.en).length, "texts");
})();
