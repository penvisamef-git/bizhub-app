// Digital Note data shared with the web: stickers (SVG), the emoji picker list, the page themes list.
//   node tool/gen_note_data.js [../bizhub/src]   → lib/features/note/nt_data.dart
const fs = require("fs");
const path = require("path");
const SRC = (process.argv[2] || path.join(__dirname, "../../bizhub/src")).replace(/\/?$/, "/");
const load = (file, names) => {
  const code = fs.readFileSync(SRC + file, "utf8").replace(/^export /gm, "").replace(/^import .*$/gm, "");
  return new Function("localStorage", `${code}\nreturn { ${names.join(", ")} };`)({ getItem: () => null, setItem: () => {} });
};
const st = load("note/stickers.js", ["STICKERS", "STICKER_GROUPS", "STICKER_GROUP_NAMES"]);
const em = load("note/emoji.js", ["EMOJI", "EMOJI_GROUPS", "EMOJI_TAB", "EMOJI_GROUP_NAMES"]);
const th = JSON.parse(fs.readFileSync(SRC + "note/noteThemes.json", "utf8"));
const q = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$").replace(/\n/g, "\\n") + "'";
const map = (o) => `{${Object.entries(o).map(([k, v]) => `${q(k)}: ${q(v)}`).join(", ")}}`;
const out = `// GENERATED by tool/gen_note_data.js from the web (bizhub/src/note: stickers.js, emoji.js, noteThemes.json) — do not edit by hand.

class NtSticker {
  final String key, group, en, km, svg;
  const NtSticker(this.key, this.group, this.en, this.km, this.svg);
  String name(bool kmLang) => kmLang ? km : en;
}

class NtTheme {
  final String key, en, km, accent;
  final List<String> tags;
  const NtTheme(this.key, this.en, this.km, this.accent, this.tags);
  String name(bool kmLang) => kmLang ? km : en;
}

const ntStickerGroups = <String>[${st.STICKER_GROUPS.map(q).join(", ")}];
const ntStickerGroupNames = <String, Map<String, String>>{'en': ${map(st.STICKER_GROUP_NAMES.en)}, 'km': ${map(st.STICKER_GROUP_NAMES.km)}};
const ntStickers = <String, NtSticker>{
${Object.values(st.STICKERS).map((s) => `  ${q(s.key)}: NtSticker(${q(s.key)}, ${q(s.group)}, ${q(s.en)}, ${q(s.km)}, ${q(s.svg)}),`).join("\n")}
};

const ntEmojiGroups = <String>[${em.EMOJI_GROUPS.map(q).join(", ")}];
const ntEmojiTab = <String, String>${map(em.EMOJI_TAB)};
const ntEmojiGroupNames = <String, Map<String, String>>{'en': ${map(em.EMOJI_GROUP_NAMES.en)}, 'km': ${map(em.EMOJI_GROUP_NAMES.km)}};
const ntEmoji = <String, List<String>>{
${Object.entries(em.EMOJI).map(([k, v]) => `  ${q(k)}: [${v.map(q).join(", ")}],`).join("\n")}
};

const ntThemes = <NtTheme>[
${th.themes.map((t) => `  NtTheme(${q(t.key)}, ${q(t.en)}, ${q(t.km)}, ${q(t.accent || "")}, [${(t.tags || []).map(q).join(", ")}]),`).join("\n")}
];
`;
fs.writeFileSync(path.join(__dirname, "../lib/features/note/nt_data.dart"), out);
console.log("stickers", Object.keys(st.STICKERS).length, "emoji", Object.values(em.EMOJI).flat().length, "themes", th.themes.length);
