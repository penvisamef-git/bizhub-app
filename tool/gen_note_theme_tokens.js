// Digital Note page themes → small colour tokens for the app's theme previews (themes shop, add-ons).
// Reads the web's bizhub/src/note/themes.css + noteThemes.json, writes lib/features/note/nt_theme_tokens.dart.
// usage: node tool/gen_note_theme_tokens.js ../bizhub/src
const fs = require("fs");
const path = require("path");
const SRC = (process.argv[2] || "../bizhub/src").replace(/\/?$/, "/");
const css = fs.readFileSync(SRC + "note/themes.css", "utf8");
const list = JSON.parse(fs.readFileSync(SRC + "note/noteThemes.json", "utf8")).themes;

// "#abc" / "#aabbcc" / "rgba(r, g, b, a)" → 0xAARRGGBB (null when not a colour)
function argb(v) {
  if (!v) return null;
  v = v.trim();
  let m = v.match(/^#([0-9a-f]{3})$/i);
  if (m) v = "#" + m[1].split("").map((c) => c + c).join("");
  m = v.match(/^#([0-9a-f]{6})$/i);
  if (m) return "0xFF" + m[1].toUpperCase();
  m = v.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)$/i);
  if (m) {
    const a = Math.round((m[4] === undefined ? 1 : Number(m[4])) * 255);
    const hx = (x) => Number(x).toString(16).padStart(2, "0").toUpperCase();
    return "0x" + hx(a) + hx(m[1]) + hx(m[2]) + hx(m[3]);
  }
  return null;
}
const block = (sel) => {
  const re = new RegExp("\\n" + sel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\s*\\{([\\s\\S]*?)\\n\\}");
  const m = css.match(re);
  return m ? m[1] : "";
};
// the page background: the colours of its last layer (a linear-gradient, or the plain colour at the end)
function pageColours(b) {
  const m = b.match(/background(?:-color)?:\s*([\s\S]*?);/);
  if (!m) return [];
  const v = m[1].replace(/!important/g, "").trim();
  // split the top-level layers
  const layers = [];
  let depth = 0,
    cur = "";
  for (const ch of v) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      layers.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) layers.push(cur.trim());
  const last = layers[layers.length - 1] || "";
  const cols = (last.match(/#[0-9a-f]{3,6}\b|rgba?\([^)]*\)/gi) || []).map(argb).filter(Boolean);
  return cols.slice(0, 3);
}
function fontOf(...blocks) {
  const f = blocks.reverse().map((b) => (b.match(/font-family:\s*([^;]+);/) || [])[1] || "").join(" ");
  if (/monospace|SF Mono|Menlo|Consolas/i.test(f)) return "mono";
  if (/Comic|Chalkboard|Marker|cursive/i.test(f)) return "hand";
  if (/Georgia|serif/i.test(f) && !/sans-serif/i.test(f.replace(/Georgia[^,]*,?/, ""))) return "serif";
  if (/Georgia|Times/i.test(f)) return "serif";
  return "sans";
}

const rows = [];
for (const t of list) {
  if (t.key === "default") {
    rows.push(`  'default': NtThemeTokens(card: 0xFFFFFFFF, ink: 0xFF16171B, muted: 0xFF6A6E7A, line: 0xFFE8EAF0, page: [0xFFF4F5F8], font: 'sans'),`);
    continue;
  }
  const b = block(`.np-th-${t.key}`);
  // the title font: any rule whose selector list has ".np-th-<key> .np-title"
  const title = [...css.matchAll(/([^{}]*)\{([^{}]*)\}/g)].filter((m) => m[1].includes(`.np-th-${t.key} .np-title`)).map((m) => m[2]).join("\n");
  const tok = (k) => argb(((b.match(new RegExp(`--${k}:\\s*([^;]+);`)) || [])[1] || "").trim());
  const page = pageColours(b);
  rows.push(
    `  '${t.key}': NtThemeTokens(card: ${tok("card") || "0xFFFFFFFF"}, ink: ${tok("ink") || "0xFF16171B"}, muted: ${tok("muted") || "0xFF6A6E7A"}, line: ${tok("line") || "0xFFE8EAF0"}, page: [${(page.length ? page : ["0xFFF4F5F8"]).join(", ")}], font: '${fontOf(b, title)}'),`,
  );
}
const out = `// GENERATED by tool/gen_note_theme_tokens.js from the web (bizhub/src/note/themes.css) — do not edit by hand.
// The colours of each Digital Note page theme, for the app's small previews (the real page is drawn by the web).

class NtThemeTokens {
  final int card, ink, muted, line;
  final List<int> page; // the page background (1 colour, or a gradient top → bottom)
  final String font; // sans | serif | mono | hand
  const NtThemeTokens({required this.card, required this.ink, required this.muted, required this.line, required this.page, required this.font});
}

const ntThemeTokens = <String, NtThemeTokens>{
${rows.join("\n")}
};
`;
fs.writeFileSync(path.join(__dirname, "../lib/features/note/nt_theme_tokens.dart"), out);
console.log("themes", rows.length);
