// the words above: ntE(ctx, 'recent'); {n}-style values are filled like the i18n texts
String ntE(NtCtx ctx, String key, [Map<String, Object?> vars = const {}]) {
  var s = (ctx.km ? _km : _en)[key] ?? _en[key] ?? key;
  vars.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}
