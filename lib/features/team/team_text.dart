String tm(String lang, String key, [Map<String, Object?> vars = const {}]) {
  var s = teamText[lang]?[key] ?? teamText['en']![key] ?? key;
  vars.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
  return s;
}

